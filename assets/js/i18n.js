// Apply language instantly across DOM
function setAppLanguage(langCode) {
  if (!SBS_TRANSLATIONS[langCode]) langCode = "en";
  localStorage.setItem("sbs_lang", langCode);

  const t = SBS_TRANSLATIONS[langCode];

  // Update selected language button text
  const labelEl = document.getElementById("selectedLangText");
  if (labelEl) labelEl.textContent = t.lang_name;

  // Translate all elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // Translate placeholders with data-i18n-ph attribute
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (t[key]) {
      el.setAttribute("placeholder", t[key]);
    }
  });

  // Translate HTML contents with data-i18n-html attribute
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });
}

// Initialize on page load
document.addEventListener("DOMContentLoaded", () => {
  const currentLang = localStorage.getItem("sbs_lang") || "en";
  setAppLanguage(currentLang);
});
